    /// <summary>
    /// Keeps the README's table of the kinds of app each step acts on in step with the step bindings. The table is worked out
    /// from the compiled bindings: a step acts on the configured target through <c>App</c>, on a model-driven app through
    /// <c>XrmApp</c> or <c>ModelDrivenApp</c>, and on a TALXIS Portal through <c>PortalApp</c>. Through <c>App</c>, a target
    /// whose implementation of an operation throws a <see cref="NotSupportedException"/> without ever returning does not
    /// support the step, and one that throws it (or calls a method that throws it) for some values supports it partly; a
    /// step that only throws a <see cref="PendingStepException"/> is not implemented and acts on neither app. A step that acts
    /// on no app object is listed only with what runs against real apps confirmed (<c>StepsWithoutApp</c>). Run the tests
    /// with the UPDATE_STEP_TABLE environment variable set to 1 to rewrite the table; the test still fails once, so that the
    /// rewritten README gets reviewed and committed.
    /// </summary>
    [TestClass]
    public class StepTargetTableTests
    {
        private const string Begin = "<!-- BEGIN STEPS BY APP: generated by StepTargetTableTests -->";
        private const string End = "<!-- END STEPS BY APP -->";
        private const string Supported = "✓";
        private const string Partly = "✓\\*";
        private const string NotSupported = "–";

        // A step without an app object that no run against a real app has used yet.
        private const string Unconfirmed = "?";

        // A step without an app object that is missing from StepsWithoutApp; the README cannot list it.
        private const string Pending = "not listed";

        private static readonly Dictionary<short, OpCode> OneByteOpCodes = OpCodesOfSize(1);
        private static readonly Dictionary<short, OpCode> TwoByteOpCodes = OpCodesOfSize(2);
        private static readonly OpCode[] LoadLocalOpCodes = { OpCodes.Ldloc_0, OpCodes.Ldloc_1, OpCodes.Ldloc_2, OpCodes.Ldloc_3 };
        private static readonly OpCode[] StoreLocalOpCodes = { OpCodes.Stloc_0, OpCodes.Stloc_1, OpCodes.Stloc_2, OpCodes.Stloc_3 };
        private static readonly HashSet<Type> TargetInterfaces = typeof(IAppUnderTest).GetProperties().Select(property => property.PropertyType).ToHashSet();

        // Implementations that throw a NotSupportedException for one value of their last (bool) parameter only, and the value;
        // steps pass the parameter as a constant (PortalGridTests checks that a TALXIS Portal refuses the disabled check).
        private static readonly Dictionary<MethodInfo, bool> UnsupportedForValue = new()
        {
            [typeof(PortalSubGrid).GetMethod(nameof(PortalSubGrid.IsCommandEnabled))!] = false,
        };

        // The steps that act on no app object (test data, record access, downloads), with where runs against real apps
        // confirmed that they work. A step that is not listed fails the table.
        private static readonly Dictionary<string, (string ModelDrivenApp, string Portal)> StepsWithoutApp = new()
        {
            // The test data steps create records through the page's Web API, or through the Web API of a separate
            // Dataverse environment (a TALXIS Portal's).
            ["Given I have created '(.*)'"] = (Supported, Supported),
            ["Given '(.*)' exists"] = (Supported, Supported),
            ["Given the following records exist"] = (Supported, Supported),
            ["Given I have created the following records"] = (Supported, Supported),

            // The page's Xrm.WebApi, to which a TALXIS Portal applies its retrieve filters.
            ["Then I should be able to read '(.*)'"] = (Supported, Supported),
            ["Then I should not be able to read '(.*)'"] = (Supported, Supported),

            // The browser's downloads folder only.
            ["Then a file should have been downloaded"] = (Supported, Supported),

            // Creates the records as another Dataverse user, impersonated by the application user; no project uses it yet.
            ["Given '(.*)' has created '(.*)'"] = (Unconfirmed, Unconfirmed),
        };

        // Worked out once: it reads the IL of every step and of everything the steps call.
        private static readonly Lazy<IReadOnlyList<(string Step, string ModelDrivenApp, string Portal)>> StepRows = new(() => Rows().ToList());

        private interface IFixtureCheck
        {
            void Check();
        }

        [DataTestMethod]
        [DataRow("Given I have created '(.*)'", Supported, Supported)]
        [DataRow("Given I have opened '(.*)'", Supported, NotSupported)]
        [DataRow("Given I am logged in to the portal as '(.*)'", NotSupported, Supported)]
        [DataRow("When I select the '([^']+)' command under the '([^']+)' flyout", Supported, NotSupported)]
        [DataRow("Then the '(.*)' subarea should be disabled with the message '(.*)'", NotSupported, Supported)]
        [DataRow("Then the '(.*)' command on the '(.*)' subgrid should be enabled", Supported, Supported)]
        [DataRow("Then the '(.*)' command on the '(.*)' subgrid should be disabled", Supported, NotSupported)]
        [DataRow("Then the record should be in the '(.*)' stage of the business process flow", NotSupported, NotSupported)]
        [DataRow("When I enter '(.*)' into the '(.*)' field on the dialog", Partly, Supported)]
        [DataRow("When I choose the '(.*)' option on the dialog", NotSupported, Supported)]
        [DataRow("Then the virtual dataset grid should contain '(.*)'", NotSupported, Supported)]
        public void WorksOutTheAppsOfAStep(string step, string modelDrivenApp, string portal)
        {
            var row = StepRows.Value.Single(row => row.Step == step);

            Assert.AreEqual((modelDrivenApp, portal), (row.ModelDrivenApp, row.Portal), step);
        }

